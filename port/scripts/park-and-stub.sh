#!/usr/bin/env bash
# Park test-only Android.bp trees AND emit stub definitions for every module
# name that parked files used to provide, so remaining modules still resolve.
#
# Why stubs: soong builds its graph from name -> definition. Park a file and its
# modules vanish; anything with `deps: ["that_name"]` then fails with
# "depends on undefined module". A stub restores the NAME without the real
# implementation. Stubs for test-only libs are never compiled into otapackage
# (nothing in the ship closure depends on them) - soong only needs the name to
# resolve. Defaults stubs are near-free.
#
# Runs inside the container: walking these trees over the host-side virtiofs
# mount exceeds any command timeout.
set -uo pipefail
cd /aosp || exit 1

STUB_DIR="device/xiaomi/rosy/lopsi_stubs"
STUB="$STUB_DIR/Android.bp"

# ---- 1. park by directory-name pattern -------------------------------------
# test / tests / testing / *-test / test_* / fuzz / benchmarks / vts / gtest
parked=0
while IFS= read -r f; do
  grep -q '^// parked' "$f" 2>/dev/null && continue
  printf '// parked - test tree (rosy otapackage memory budget)\n' >"$f"
  parked=$((parked + 1))
done < <(
  find . -name Android.bp \
    -not -path './out/*' -not -path './.repo/*' -not -path './prebuilts/*' \
    -not -path './external/*' \
    -not -path './build/*' -not -path './art/*' -not -path './system/lib*' \
    \( -path '*/test/*' -o -path '*/tests/*' -o -path '*/testing/*' \
       -o -path '*/test_*/*' -o -path '*/vts/*' -o -path '*/fuzz/*' \
       -o -path '*/benchmarks/*' -o -path '*/gtest/*' -o -path '*/hosttests/*' \) \
    2>/dev/null
)
echo "PARKED_PATTERN $parked files"
# ---- 2. emit stubs for undefined module names ------------------------------
# Names are read from the recorded error list. Each becomes the cheapest module
# type that satisfies a `deps:` entry:
#   *defaults / *Defaults / *.defaults -> defaults (pure flag bundle, no build)
#   .txt / .ndk / llndk.*                -> filegroup (data, no compile)
#   everything else                      -> java_library with no srcs (empty jar)
# Empty modules still occupy graph nodes, so this REDUCES peak heap far less
# than parking does - it exists purely to satisfy the dependency graph.
STUB_LIST="${STUB_LIST:-/port/scripts/undefined-modules.txt}"
if [ -f "$STUB_LIST" ]; then
  mkdir -p "$STUB_DIR"
  {
    echo "// AUTO-GENERATED by scripts/park-and-stub.sh - do not edit."
    echo "// Stub definitions so modules parked for memory reasons stay"
    echo "// resolvable by dependents. Test-only; not shipped in otapackage."
    echo 'package {'
    echo '    default_applicable_licenses: ["Android-Apache-2.0"],'
    echo '}'
    echo ''
    while IFS= read -r name || [ -n "$name" ]; do
      case "$name" in ''|'#'*) continue ;; esac
      case "$name" in
        *defaults|*Defaults|*.defaults)
          # defaults is the cheapest node type: a flag bundle with no build edges.
          echo "defaults { name: \"$name\", }" ;;
        *.txt|*.ndk|llndk.*|vndk*.libraries.*)
          # Data lists (VNDK/LLNDK library manifests): filegroup, no compile.
          echo "filegroup { name: \"$name\", }" ;;
        *)
          # Everything else must keep the EXACT name dependents reference, or
          # the "undefined module" error simply moves to the next module. An
          # empty java_library is the least invasive real module: it produces a
          # jar, satisfies java deps, and costs one node.
          echo "java_library { name: \"$name\", srcs: [], installable: false, }"
      esac
    done <"$STUB_LIST"
  } >"$STUB"
  echo "STUB_WRITTEN $STUB ($(grep -c 'name:' "$STUB") defs)"
else
  echo "STUB_SKIPPED no $STUB_LIST"
fi
